def rings(name,rs,n=40):
 # rings = z, center x, center y, radius x, radius y, phase
 # Extra vertical subdivisions support softly flowing cloth rather than rigid tubes.
 expanded=[]
 for j in range(len(rs)-1):
  for q in range(3):
   t=q/3;expanded.append(tuple((1-t)*a+t*b for a,b in zip(rs[j],rs[j+1])))
 expanded.append(rs[-1]);rs=expanded
 vs=[]
 for k,(z,cx,cy,rx,ry,phase) in enumerate(rs):
  for i in range(n):
   a=2*math.pi*i/n; wave=1+.065*math.sin(5*a+phase)+.025*math.sin(9*a-phase)
   drift=.008*(.86-z) if 'body' in name else .003*math.sin(z*6+phase)
   fold=.004*math.sin(7*a+.9*math.sin(z*4))*(1-.35*z)
   vs.append((cx+drift+rx*math.cos(a)*wave,cy+ry*math.sin(a)*wave+fold,z+.003*math.sin(3*a+phase)))
 fs=[]
 for j in range(len(rs)-1):
  for i in range(n):fs.append((j*n+i,j*n+(i+1)%n,(j+1)*n+(i+1)%n,(j+1)*n+i))
 o=mesh_obj(name,vs,fs,wool);uv=o.data.uv_layers.new(name='UVMap')
 for p in o.data.polygons:
  for li in p.loop_indices:
   vi=o.data.loops[li].vertex_index; ring=vi//n; a=vi%n
   # wrap seam to the neighboring final segment
   if p.index%n==n-1 and a==0: u=1.0
   else:u=a/n
   uv.data[li].uv=(u,ring/(len(rs)-1))
 for p in o.data.polygons:p.use_smooth=True
 sol=o.modifiers.new('Fabric thickness','SOLIDIFY');sol.thickness=.0025
 return o
